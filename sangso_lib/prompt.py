    weekday = "월화수목금토일"[today.weekday()]
    system = SYSTEM.format(min1=min1, min2=min2)
    user = USER.format(today=f"{today:%Y년 %m월 %d일} ({weekday}요일)", topic1=t1, topic2=t2,
                       profile=profile, recent=recent, cc_history=cc_history, ai_history=ai_history)
    return system, user
